// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// no-token protocols at or above the snapshot's own $5M floor until the board clears the gate's
// 100-row floor. A protocol is no-token when its index entry records no token (no market cap, no
// CoinGecko id, no symbol) and it is not a wrapped, staked or bridged product of a token that already
// trades; the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   category_mult = the multiple of TVL a category's tokens have historically traded at
//                   (liquid staking 8x, DEX/lending 5x, infra/wallet 10x, everything else 3x)
//   growth_adj    = clamp(1 + change_7d / 200, 0.5, 2)   (change_7d unknown: 0)
//   growth_value  = tvl_usd x category_mult x growth_adj
//   implied       = max(1,000,000, round((1 - tvl_weight) x growth_value + tvl_weight x tvl_usd))
//
// tvl_weight is the share of every value that comes from pure TVL rather than the growth-adjusted
// multiple, so a deep, proven protocol is not left entirely to its category. The constants are the
// house model's, stated in the dashboard and changeable in the model sandbox.
// No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  min_implied_usd: number;
  growth_divisor: number;
  growth_floor: number;
  growth_cap: number;
  tvl_weight: number;
  mult_liquid_staking: number;
  mult_dex_lending: number;
  mult_infra_wallet: number;
  mult_rest: number;
}

export const MODEL: ModelConstants = {
  min_implied_usd: 1_000_000,
  growth_divisor: 200,
  growth_floor: 0.5,
  growth_cap: 2,
  tvl_weight: 0.3,
  mult_liquid_staking: 8,
  mult_dex_lending: 5,
  mult_infra_wallet: 10,
  mult_rest: 3,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

/** The fewest rows a valid board carries: the gate's floor. */
export const MIN_BOARD_ROWS = 100;

/** The lowest TVL an extra no-token protocol needs to join the board: the snapshot's own floor. */
export const MIN_TVL_USD = 5_000_000;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** A farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

